CREATE DATABASE IF NOT EXISTS reciclame_esta
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS 'reciclame_esta'@'localhost'
  IDENTIFIED BY 'CAMBIA_ESTA_CONTRASENA';

GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, INDEX, ALTER, REFERENCES
  ON reciclame_esta.* TO 'reciclame_esta'@'localhost';

USE reciclame_esta;

CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  nombre VARCHAR(160) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  rol ENUM('usuario', 'admin') NOT NULL DEFAULT 'usuario',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) NOT NULL PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  expires_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_sessions_expiration (expires_at),
  CONSTRAINT fk_sessions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS residuos (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS puntos (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(180) NOT NULL,
  calle VARCHAR(180) NOT NULL DEFAULT '',
  colonia VARCHAR(120) NOT NULL DEFAULT '',
  alcaldia VARCHAR(100) NOT NULL DEFAULT '',
  cp CHAR(5) NOT NULL DEFAULT '',
  lat DECIMAL(10, 7) NULL,
  lng DECIMAL(10, 7) NULL,
  residuos JSON NOT NULL,
  horarios JSON NOT NULL,
  ficha JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_puntos_alcaldia (alcaldia)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS reportes (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  punto_id INT UNSIGNED NULL,
  punto_nombre VARCHAR(180) NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  usuario VARCHAR(160) NOT NULL,
  motivo VARCHAR(100) NOT NULL,
  descripcion VARCHAR(2000) NOT NULL,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado ENUM('Nuevo', 'Alta', 'Devuelto') NOT NULL DEFAULT 'Nuevo',
  respuesta_admin VARCHAR(500) NOT NULL DEFAULT '',
  INDEX idx_reportes_usuario (user_id),
  INDEX idx_reportes_estado (estado),
  CONSTRAINT fk_reportes_punto FOREIGN KEY (punto_id) REFERENCES puntos(id) ON DELETE SET NULL,
  CONSTRAINT fk_reportes_usuario FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bitacora (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  admin_id INT UNSIGNED NOT NULL,
  admin VARCHAR(160) NOT NULL,
  accion VARCHAR(120) NOT NULL,
  detalle VARCHAR(500) NOT NULL,
  INDEX idx_bitacora_fecha (fecha),
  CONSTRAINT fk_bitacora_admin FOREIGN KEY (admin_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
