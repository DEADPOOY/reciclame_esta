-- ahi va asta arriba del todo
-- Esquema PostgreSQL para Supabase. El servidor Express aplica este archivo
-- al iniciar. Ejecútalo también manualmente en Supabase SQL Editor antes de
-- importar la información de la base MySQL existente.

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  nombre VARCHAR(160) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  rol TEXT NOT NULL DEFAULT 'usuario' CHECK (rol IN ('usuario', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sessions_expiration ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS residuos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS puntos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(180) NOT NULL,
  calle VARCHAR(180) NOT NULL DEFAULT '',
  colonia VARCHAR(120) NOT NULL DEFAULT '',
  alcaldia VARCHAR(100) NOT NULL DEFAULT '',
  cp CHAR(5) NOT NULL DEFAULT '',
  lat NUMERIC(10, 7),
  lng NUMERIC(10, 7),
  residuos JSONB NOT NULL DEFAULT '[]'::jsonb,
  horarios JSONB NOT NULL DEFAULT '{}'::jsonb,
  ficha JSONB NOT NULL DEFAULT '{"numero":"","fecha":"","archivo":"","estado":"pendiente"}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_puntos_alcaldia ON puntos(alcaldia);

CREATE TABLE IF NOT EXISTS reportes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  punto_id BIGINT REFERENCES puntos(id) ON DELETE SET NULL,
  punto_nombre VARCHAR(180) NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  usuario VARCHAR(160) NOT NULL,
  motivo VARCHAR(100) NOT NULL,
  descripcion VARCHAR(2000) NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado TEXT NOT NULL DEFAULT 'Nuevo' CHECK (estado IN ('Nuevo', 'Alta', 'Devuelto')),
  respuesta_admin VARCHAR(500) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_reportes_usuario ON reportes(user_id);
CREATE INDEX IF NOT EXISTS idx_reportes_estado ON reportes(estado);

CREATE TABLE IF NOT EXISTS bitacora (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  admin_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  admin VARCHAR(160) NOT NULL,
  accion VARCHAR(120) NOT NULL,
  detalle VARCHAR(500) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_bitacora_fecha ON bitacora(fecha);

-- La aplicación conserva su autorización en Express y solo accede desde el
-- servidor. No habilitar acceso anónimo a estas tablas desde el navegador.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE residuos ENABLE ROW LEVEL SECURITY;
ALTER TABLE puntos ENABLE ROW LEVEL SECURITY;
ALTER TABLE reportes ENABLE ROW LEVEL SECURITY;
ALTER TABLE bitacora ENABLE ROW LEVEL SECURITY;
